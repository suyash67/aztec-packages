//! Emits a C++ header of Orchard test vectors from the production `orchard` crate (with the local export patch):
//! Pasta hash-to-curve outputs for every Orchard generator, and complete Action witnesses + public inputs.

use ff::PrimeField;
use group::{Curve, Group};
use orchard::{
    builder::{Builder, BundleType},
    bundle::BundleVersion,
    keys::{FullViewingKey, Scope, SpendingKey},
    note::{Note, NoteVersion, RandomSeed, Rho},
    tree::{MerkleHashOrchard, MerklePath},
    value::NoteValue,
    Bundle,
};
use pasta_curves::{arithmetic::CurveAffine, arithmetic::CurveExt, pallas};
use rand::{rngs::StdRng, Rng, SeedableRng};

fn fe<F: PrimeField<Repr = [u8; 32]>>(f: &F) -> String {
    let mut s = String::from("0x");
    for b in f.to_repr().iter().rev() {
        s.push_str(&format!("{:02x}", b));
    }
    s
}

fn point(p: pallas::Point) -> String {
    let a = p.to_affine();
    let c = a.coordinates().unwrap();
    format!("{{ \"{}\", \"{}\" }}", fe(c.x()), fe(c.y()))
}

fn emit_action(name: &str, witness: &[(String, String)], public_inputs: &[String]) {
    println!("inline const ActionVector {name} = {{");
    println!("    .witness = {{");
    for (k, v) in witness {
        println!("        {{ \"{k}\", \"{v}\" }},");
    }
    println!("    }},");
    println!("    .public_inputs = {{");
    for v in public_inputs {
        println!("        \"{v}\",");
    }
    println!("    }},");
    println!("}};");
}

fn main() {
    println!("// Generated by orchard_vectors (orchard 0.16.0 + pasta_curves 0.6). Do not edit by hand.");
    println!("#pragma once");
    println!("#include <string>");
    println!("#include <utility>");
    println!("#include <vector>");
    println!("namespace bb::zcash::test_vectors {{");
    println!("struct PointHex {{ const char* x; const char* y; }};");
    println!("struct GroupHashVector {{ const char* domain; std::vector<uint8_t> message; PointHex point; }};");
    println!("struct ActionVector {{ std::vector<std::pair<std::string, std::string>> witness; std::vector<std::string> public_inputs; }};");

    // ---- GroupHash vectors
    let mut ghs: Vec<(&str, Vec<u8>)> = vec![
        ("z.cash:test", b"Trans rights now!".to_vec()),
        ("z.cash:Orchard", b"G".to_vec()),
        ("z.cash:Orchard", b"K".to_vec()),
        ("z.cash:Orchard-cv", b"v".to_vec()),
        ("z.cash:Orchard-cv", b"r".to_vec()),
        ("z.cash:Orchard-NoteCommit-r", vec![]),
        ("z.cash:Orchard-CommitIvk-r", vec![]),
        ("z.cash:SinsemillaQ", b"z.cash:Orchard-MerkleCRH".to_vec()),
        ("z.cash:SinsemillaQ", b"z.cash:Orchard-NoteCommit-M".to_vec()),
        ("z.cash:SinsemillaQ", b"z.cash:Orchard-CommitIvk-M".to_vec()),
    ];
    for m in [0u32, 1, 2, 511, 1023] {
        ghs.push(("z.cash:SinsemillaS", m.to_le_bytes().to_vec()));
    }
    println!("inline const std::vector<GroupHashVector> GROUP_HASH_VECTORS = {{");
    for (d, msg) in &ghs {
        let p = pallas::Point::hash_to_curve(d)(msg);
        let bytes: Vec<String> = msg.iter().map(|b| format!("{b}")).collect();
        println!("    {{ \"{d}\", {{ {} }}, {} }},", bytes.join(", "), point(p));
    }
    println!("}};");
    let v = pasta_curves::vesta::Point::hash_to_curve("z.cash:test")(b"hello").to_affine();
    let c = v.coordinates().unwrap();
    println!("inline const PointHex VESTA_HASH_TO_CURVE_HELLO = {{ \"{}\", \"{}\" }};", fe(c.x()), fe(c.y()));

    // ---- Action vectors
    let mut rng = StdRng::seed_from_u64(0x5a5a_2026);
    let version = BundleVersion::orchard_v2();
    let flags = version.default_flags();

    // (1) one Action with a real spend at a random tree position and a real output
    {
        let sk = SpendingKey::from_bytes([7; 32]).unwrap();
        let fvk = FullViewingKey::from(&sk);
        let recipient = fvk.address_at(0u32, Scope::External);
        let note = loop {
            let mut rho = [0u8; 32];
            rng.fill_bytes(&mut rho);
            let rho = Rho::from_bytes(&rho);
            if rho.is_none().into() {
                continue;
            }
            let rho = rho.unwrap();
            let mut rseed = [0u8; 32];
            rng.fill_bytes(&mut rseed);
            let rseed = RandomSeed::from_bytes(rseed, &rho);
            if rseed.is_none().into() {
                continue;
            }
            let n = Note::from_parts(recipient, NoteValue::from_raw(5_000_000), rho, rseed.unwrap(), NoteVersion::V2);
            if n.is_some().into() {
                break n.unwrap();
            }
        };
        let mut auth_path = [MerkleHashOrchard::from_bytes(&[0u8; 32]).unwrap(); 32];
        for node in auth_path.iter_mut() {
            loop {
                let mut b = [0u8; 32];
                rng.fill_bytes(&mut b);
                b[31] &= 0x3f;
                let h = MerkleHashOrchard::from_bytes(&b);
                if h.is_some().into() {
                    *node = h.unwrap();
                    break;
                }
            }
        }
        let pos: u32 = rng.next_u32();
        let path = MerklePath::from_parts(pos, auth_path);
        let cmx = note.commitment().into();
        let anchor = path.root(cmx);

        let sk2 = SpendingKey::from_bytes([9; 32]).unwrap();
        let recipient2 = FullViewingKey::from(&sk2).address_at(3u32, Scope::External);
        let mut builder = Builder::new(
            BundleType::Transactional { bundle_required: true, pad_to_minimum: Some(1) },
            version,
            flags,
            anchor,
        )
        .unwrap();
        builder.add_spend(fvk, note, path).unwrap();
        builder.add_output(None, recipient2, NoteValue::from_raw(4_000_000), [0; 512]).unwrap();
        let bundle: Bundle<_, i64> = builder.build(&mut rng).unwrap().unwrap().0;
        assert_eq!(bundle.actions().len(), 1);
        let circuit = &bundle.authorization().export_circuits()[0];
        let instance = bundle.actions()[0].to_instance(*bundle.flags(), *bundle.anchor());
        emit_action("ACTION_REAL_SPEND", &circuit.export_witness(), &instance.export_public_inputs());
    }

    // (2) output-only Actions: dummy spends with v_old = 0 whose anchor check is disabled
    {
        let sk = SpendingKey::from_bytes([11; 32]).unwrap();
        let recipient = FullViewingKey::from(&sk).address_at(1u32, Scope::External);
        let mut builder = Builder::new(
            BundleType::Transactional { bundle_required: true, pad_to_minimum: Some(1) },
            version,
            flags,
            orchard::Anchor::from_bytes([0; 32]).unwrap(),
        )
        .unwrap();
        builder.add_output(None, recipient, NoteValue::from_raw(123_456), [0; 512]).unwrap();
        builder.add_output(None, recipient, NoteValue::from_raw(0), [0; 512]).unwrap();
        let bundle: Bundle<_, i64> = builder.build(&mut rng).unwrap().unwrap().0;
        assert_eq!(bundle.actions().len(), 2);
        for (i, a) in bundle.actions().iter().enumerate() {
            let circuit = &bundle.authorization().export_circuits()[i];
            let instance = a.to_instance(*bundle.flags(), *bundle.anchor());
            emit_action(&format!("ACTION_DUMMY_SPEND_{i}"), &circuit.export_witness(), &instance.export_public_inputs());
        }
    }
    let _ = pallas::Point::generator();
    println!("}} // namespace bb::zcash::test_vectors");
}
