int main(int argc, char** argv)
{
    std::string output_dir = "src/barretenberg/ultra_fflonk/solidity/test";
    size_t num_vectors = 8;
    for (int i = 1; i < argc; ++i) {
        const std::string argument = argv[i];
        if (argument == "-o" && i + 1 < argc) {
            output_dir = argv[++i];
        } else if (argument == "--vectors" && i + 1 < argc) {
            num_vectors = static_cast<size_t>(std::stoul(argv[++i]));
        }
    }

    srs::init_file_crs_factory(srs::bb_crs_path());

    write(output_dir + "/RelationVectors.sol", emit_relation_vectors(num_vectors));

    std::vector<ExportedCase> cases;
    const auto add_case = [&](const std::string& label, Builder builder) {
        const auto start = std::chrono::steady_clock::now();
        ProvingKey key = preprocess(builder);
        const auto preprocessed = std::chrono::steady_clock::now();
        Proof proof = prove(key);
        const auto proven = std::chrono::steady_clock::now();
        const bool ok = verify(key.verification_key, proof, key.public_inputs());
        const auto verified = std::chrono::steady_clock::now();

        if (!ok) {
            std::cerr << "ultra-fflonk-solidity-export: refusing to write a proof its own verifier rejects"
                      << "\n";
            std::abort();
        }

        const auto ms = [](auto from, auto to) {
            return static_cast<double>(std::chrono::duration_cast<std::chrono::microseconds>(to - from).count()) /
                   1000.0;
        };
        std::cout << "ultra-fflonk-solidity-export: " << label << ", " << key.circuit_size() << " rows, "
                  << key.public_inputs().size() << " public inputs, proof " << Proof::SIZE_IN_BYTES
                  << " bytes | preprocess " << ms(start, preprocessed) << " ms, prove " << ms(preprocessed, proven)
                  << " ms, verify " << ms(proven, verified) << " ms" << "\n";

        cases.push_back(ExportedCase{ .label = label, .key = std::move(key), .proof = proof });
    };

    add_case("arithmetic", arithmetic_circuit(/*num_public_inputs=*/4, /*num_gates=*/16));
    add_case("every-gate", assorted_circuit());
    add_case("arithmetic-large", arithmetic_circuit(/*num_public_inputs=*/4, /*num_gates=*/6000));

    write(output_dir + "/Fixture.sol", emit_fixture(cases));
    return 0;
}
